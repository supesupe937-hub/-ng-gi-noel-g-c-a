-- Tinh lai tong tien o phia database theo bang gia admin da luu,
-- khong tin tong tien do trinh duyet khach gui len.
create or replace function public.set_order_total_from_current_prices()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  cfg jsonb;
  service_price integer;
  gift_total integer;
begin
  select config into cfg from public.site_settings where id = true;
  select coalesce((item->>'price')::integer, 0) into service_price
  from jsonb_array_elements(coalesce(cfg->'packages','[]'::jsonb)) item
  where item->>'name' = new.package
  limit 1;
  if service_price is null then
    raise exception 'Goi dich vu khong hop le';
  end if;
  select coalesce(sum(
    coalesce((product->>'price')::integer,0) * greatest(coalesce((gift->>'qty')::integer,0),0)
  ),0)::integer into gift_total
  from jsonb_array_elements(coalesce(new.gifts,'[]'::jsonb)) gift
  join jsonb_array_elements(coalesce(cfg->'products','[]'::jsonb)) product
    on product->>'id' = gift->>'id';
  new.total := service_price + gift_total;
  return new;
end;
$$;
drop trigger if exists orders_set_total_before_insert on public.orders;
create trigger orders_set_total_before_insert
before insert on public.orders
for each row execute function public.set_order_total_from_current_prices();

